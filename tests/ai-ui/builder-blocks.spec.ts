  await inspector.getByLabel('Limite do mês em reais').press('Enter')
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect.poll(() => store.matching('PATCH', '/api/ai/agents/a-duda').length).toBe(1)
  const body = store.matching('PATCH', '/api/ai/agents/a-duda')[0].body!
