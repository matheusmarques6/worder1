for (const processing of [false, true]) {
  test(`IA-28 source preview distinguishes empty and processing (${processing})`, async ({ page, store }) => {
    const note = store.notes.find(n => n.id === 's3')!
    note.body_markdown = ''; note.status = processing ? 'processing' : 'ready'
    let release!: () => void
    store.gates.set('GET /api/ai/knowledge/s3', new Promise<void>(resolve => { release = resolve }))
    try {
      await openBuilder(page); await pickNode(page, 'Política de troca')
      await expect(page.locator('.w-prev')).toHaveText('Carregando…')
    } finally { release() }
    await expect(page.locator('.w-prev')).toContainText(processing ? 'Conteúdo em processamento' : 'Esta fonte não tem texto para mostrar')
  })
}

