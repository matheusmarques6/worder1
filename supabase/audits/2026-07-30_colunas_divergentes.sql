-- POR QUE ESTE ARQUIVO EXISTE
--
-- O 2026-07-30_bloco2_pendentes.sql confere 294 colunas — todas vindas
-- de ALTER TABLE ADD COLUMN. Colunas declaradas DENTRO do CREATE TABLE
-- nunca foram conferidas. Uma tabela criada com formato divergente
-- passava por APLICADA.
--
-- Foi essa lacuna que deixou passar o erro mais frequente do banco:
--   column abandoned_carts.status does not exist   (60x/hora nos logs)
--
-- A MECANICA, confirmada em producao:
--   As tres migrations que definem abandoned_carts declaram `status`.
--   Todas usam CREATE TABLE IF NOT EXISTS. A tabela ja existia com outro
--   formato, entao as tres pularam INTEIRAS — nenhuma reconciliou coluna.
--   Depois, CREATE INDEX ... ON abandoned_carts(status) levanta 42703 e
--   ABORTA a migration ali. Tudo abaixo daquele ponto nunca roda.
--
--   Isso explica as 28 migrations PARCIAL de uma vez: nao sao 28
--   acidentes independentes, e este mecanismo se repetindo.
--
-- Este arquivo confere as 1947 colunas declaradas em CREATE TABLE, nas 137
