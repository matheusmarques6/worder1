      || (SELECT count(*)::text FROM estado WHERE tabela_existe) || ' colunas conferidas em '
      || (SELECT count(DISTINCT tabela)::text FROM estado WHERE tabela_existe) || ' tabelas existentes)' AS detalhe,
         NULL::text AS declarada_em

  UNION ALL

  SELECT 1,
         d.tabela
           || '  (' || count(*)::text || ' faltando'
           || CASE WHEN a.n_definicoes IS NOT NULL
                   THEN ', FORMATO AMBIGUO: ' || a.n_definicoes || ' definicoes'
                   ELSE '' END
           || ')',
         string_agg(d.coluna, ', ' ORDER BY d.coluna),
         (array_agg(d.origem ORDER BY d.coluna))[1]
  FROM divergente d
  LEFT JOIN ambigua a ON a.tabela = d.tabela
  GROUP BY d.tabela, a.n_definicoes

) rel
ORDER BY ord, detalhe DESC;
