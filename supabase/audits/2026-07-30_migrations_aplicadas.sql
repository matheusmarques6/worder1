unico AS (
  SELECT DISTINCT tipo_nome, obj, existe FROM rotulo
)
SELECT * FROM (

  -- secao 1: resumo -----------------------------------------------------
  SELECT 1 AS ord, '1. RESUMO' AS secao, tipo_nome AS item,
         count(*) FILTER (WHERE NOT existe)::text || ' de ' || count(*)::text
           || ' faltando' AS status,
         CASE WHEN count(*) FILTER (WHERE NOT existe) = 0
              THEN 'ok' ELSE 'ver secao 3' END AS detalhe
  FROM unico GROUP BY tipo_nome

  UNION ALL
  SELECT 1, '1. RESUMO', 'TOTAL',
         count(*) FILTER (WHERE NOT existe)::text || ' de ' || count(*)::text
           || ' faltando',
         CASE WHEN count(*) FILTER (WHERE NOT existe) = 0
              THEN 'banco bate com o repo' ELSE 'divergencia' END
  FROM unico

  -- secao 2: status por migration ---------------------------------------
  UNION ALL
  SELECT 2, '2. MIGRATION', arquivo,
         CASE WHEN count(*) FILTER (WHERE NOT existe) = 0 THEN 'APLICADA'
              WHEN count(*) FILTER (WHERE existe)     = 0 THEN 'NAO_APLICADA'
              ELSE 'PARCIAL' END,
         count(*) FILTER (WHERE existe)::text || '/' || count(*)::text
           || ' objetos presentes'
  FROM rotulo GROUP BY arquivo

  -- secao 3: o que falta -------------------------------------------------
  UNION ALL
  SELECT 3, '3. FALTANDO', u.tipo_nome || ': ' || u.obj, 'AUSENTE',
         'declarado em ' || (
           SELECT string_agg(DISTINCT r.arquivo, ', ' ORDER BY r.arquivo)
           FROM rotulo r WHERE r.obj = u.obj AND r.tipo_nome = u.tipo_nome)
  FROM unico u WHERE NOT u.existe

