verificado AS (
  SELECT e.arquivo, e.tipo, e.obj,
    CASE e.tipo
      WHEN 't' THEN EXISTS (
        SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = split_part(e.obj,'.',1)
          AND c.relname  = split_part(e.obj,'.',2)
          AND c.relkind IN ('r','p','v','m','f'))
      WHEN 'f' THEN EXISTS (
        SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
        WHERE n.nspname = split_part(e.obj,'.',1)
          AND p.proname  = split_part(e.obj,'.',2))
      WHEN 'c' THEN EXISTS (
        SELECT 1 FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public'
          AND c.relname = split_part(e.obj,'.',1)
          AND a.attname = split_part(e.obj,'.',2)
          AND a.attnum > 0 AND NOT a.attisdropped)
      WHEN 'i' THEN EXISTS (
        SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relname = e.obj AND c.relkind = 'i')
    END AS existe
  FROM esperado e
),
rotulo AS (
  SELECT *, CASE tipo WHEN 't' THEN 'tabela' WHEN 'f' THEN 'funcao'
                      WHEN 'c' THEN 'coluna' ELSE 'indice' END AS tipo_nome
  FROM verificado
